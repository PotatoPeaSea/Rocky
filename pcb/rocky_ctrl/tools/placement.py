def leg_parts():
    """Leg connector + series R + ESD + 22u cap, laid out radially inward of each connector."""
    out = {}
    for leg in range(1, 6):
        a = LEG_CONN_ANG[leg]
        cx, cy = pol(LEG_CONN_R, a)
        rot = a - 90
        out['J%d' % (4 + leg)] = (cx, cy, rot)
        ur = (math.cos(math.radians(a)), math.sin(math.radians(a)))
        ut = (-ur[1], ur[0])

        def at(dr, dt):
            return (round(cx + ur[0] * dr + ut[0] * dt, 2), round(cy + ur[1] * dr + ut[1] * dt, 2))
        dr = LEG_PART_DR.get(leg, -6.5)
        out['R%d' % (46 + leg)] = at(dr, -3.5) + (rot + 90,)
        out['D%d' % (4 + leg)] = at(dr, 0.5) + (rot + 90,)
        out['C%d' % (38 + leg)] = at(dr, 5.0) + (rot + 90,)
    return out


